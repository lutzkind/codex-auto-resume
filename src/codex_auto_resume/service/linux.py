"""Linux (and WSL) backend: the ``systemd --user`` unit, unchanged.

The unit, its environment and every ``systemctl --user`` call keep exactly the
behaviour that was verified live before the cross-platform work: a single
per-user service, ``Restart=on-failure`` with rate limiting disabled,
``KillMode=process`` so an in-flight resume is never signalled, and
``WantedBy=default.target`` so it starts at login (and at boot with lingering).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Optional

from .base import ServiceBackend, ServiceError, run_command

UNIT_NAME = "codex-auto-resume-helper.service"

HOST_TEMPLATE = """# Generated by `codex-auto-resume install-service`.
# It runs the quota-reset waiter outside the Codex process so it survives the
# terminal, the SSH session, and (with lingering enabled) a reboot.
[Unit]
Description=codex-auto-resume helper: wait for the Codex quota reset and resume the exact session
Documentation={documentation}
After=default.target
# A long wait must never be disabled by start rate limiting, and it must come
# back on its own if anything kills it.
StartLimitIntervalSec=0

[Service]
Type=simple
Restart=on-failure
RestartSec=15
KillMode=process
TimeoutStartSec=infinity
ExecStart={python} -m codex_auto_resume helper --state-dir {state_dir}{codex_home_arg}{codex_bin_arg}
Environment=PYTHONPATH={package_parent}
Environment=CODEX_AUTO_RESUME_CODEX_BIN={codex_bin}
Environment=PYTHONUNBUFFERED=1
StandardOutput=append:{stdout}
StandardError=append:{stdout}

[Install]
WantedBy=default.target
"""


def unit_dir() -> Path:
    return Path.home() / ".config" / "systemd" / "user"


def unit_path() -> Path:
    return unit_dir() / UNIT_NAME


def package_parent() -> str:
    """Directory that must be on PYTHONPATH for ``-m codex_auto_resume``."""
    import codex_auto_resume

    return os.path.dirname(os.path.dirname(os.path.abspath(codex_auto_resume.__file__)))


def render_unit(
    codex_bin: Optional[str],
    documentation: str = "https://github.com/lutzkind/codex-auto-resume",
    python: Optional[str] = None,
    stdout: Optional[str] = None,
    state_dir: Optional[str] = None,
    codex_home: Optional[str] = None,
) -> str:
    """The exact unit text ``install-service`` writes (pure, testable).

    The state directory (and ``CODEX_HOME`` when one was set explicitly at
    install time) are passed explicitly so the helper does not depend on the
    user manager's environment.
    """
    from .. import paths

    def _arg(flag: str, value: Optional[str]) -> str:
        return f" {flag} {value}" if value else ""

    return HOST_TEMPLATE.format(
        documentation=documentation,
        python=(python or sys.executable),
        package_parent=package_parent().replace("%", "%%"),
        codex_bin=(codex_bin or "codex").replace("%", "%%"),
        stdout=(stdout or str(paths.log_file())).replace("%", "%%"),
        state_dir=str(state_dir or paths.state_dir()).replace("%", "%%"),
        codex_home_arg=_arg("--codex-home", codex_home).replace("%", "%%"),
        codex_bin_arg=_arg("--codex-bin", codex_bin).replace("%", "%%"),
    )


def _systemctl(*args: str, check: bool = True) -> str:
    completed = run_command(["systemctl", "--user", *args], check=check)
    return completed.stdout


def install_unit(codex_bin: Optional[str]) -> Path:
    from .. import paths

    paths.ensure_dirs()
    unit_dir().mkdir(parents=True, exist_ok=True)
    content = render_unit(codex_bin, codex_home=os.environ.get(paths.ENV_CODEX_HOME))
    target = unit_path()
    if target.exists():
        target.replace(target.with_suffix(target.suffix + ".bak"))
    target.write_text(content, encoding="utf-8")
    _systemctl("daemon-reload")
    _systemctl("enable", UNIT_NAME)
    return target


def uninstall_unit() -> None:
    _systemctl("disable", "--now", UNIT_NAME)
    target = unit_path()
    if target.exists():
        target.unlink()
    _systemctl("daemon-reload")
    if target.exists():
        raise RuntimeError(f"could not remove {target}")


def service_state() -> dict:
    active = _systemctl("is-active", UNIT_NAME, check=False).strip()
    enabled = _systemctl("is-enabled", UNIT_NAME, check=False).strip()
    return {"active": active, "enabled": enabled, "unit": str(unit_path())}


class LinuxBackend(ServiceBackend):
    name = "systemd"
    display = "systemd --user"

    def available(self) -> tuple[bool, str]:
        """Whether a usable user manager exists (WSL without systemd: no)."""
        if not unit_dir().parent.exists() and not _systemctl_available():
            return False, "systemd user instance not found"
        completed = run_command(["systemctl", "--user", "show-environment"], check=False)
        if completed.returncode != 0:
            detail = (completed.stdout or "").strip() or "systemctl --user unavailable"
            return False, detail
        return True, "systemd user instance available"

    def artifact_path(self) -> Optional[Path]:
        return unit_path()

    def install(self, codex_bin: Optional[str]) -> str:
        available, detail = self.available()
        if not available:
            raise ServiceError(
                "systemd user services are unavailable on this machine "
                f"({detail}); see `codex-auto-resume doctor`"
            )
        return str(install_unit(codex_bin))

    def uninstall(self) -> None:
        uninstall_unit()

    def start(self) -> None:
        _systemctl("start", "--no-block", UNIT_NAME)

    def stop(self) -> None:
        _systemctl("stop", UNIT_NAME)

    def status(self) -> dict:
        try:
            state = service_state()
        except (OSError, RuntimeError) as error:
            state = {"active": "unavailable", "enabled": "unavailable", "unit": str(unit_path())}
            detail = str(error)
        else:
            detail = ""
        return {
            "backend": self.name,
            "display": self.display,
            "installed": unit_path().exists(),
            "active": state["active"],
            "enabled": state["enabled"],
            "artifact": state["unit"],
            "detail": detail,
            "start_hint": f"systemctl --user start {UNIT_NAME}",
        }


def _systemctl_available() -> bool:
    try:
        return bool(run_command(["systemctl", "--version"], check=False).returncode == 0)
    except ServiceError:
        return False
