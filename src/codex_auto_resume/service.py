"""Install or remove the user-level systemd unit that runs the helper."""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Optional

UNIT_NAME = "codex-auto-resume-helper.service"

UNIT_TEMPLATE = """# Generated by `codex-auto-resume install-service`.
# It runs the quota-reset waiter outside the Codex process so it survives the
# terminal, the SSH session, and (with lingering enabled) a reboot.
[Unit]
Description=codex-auto-resume helper: wait for the Codex quota reset and resume the exact session
Documentation={documentation}
After=default.target

[Service]
Type=simple
Restart=no
KillMode=process
TimeoutStartSec=infinity
ExecStart={python} {cli} helper
Environment=CODEX_AUTO_RESUME_CODEX_BIN={codex_bin}
Environment=PYTHONUNBUFFERED=1
StandardOutput=append:{stdout}
StandardError=append:{stdout}

[Install]
WantedBy=default.target
"""


def _unit_dir() -> Path:
    return Path.home() / ".config" / "systemd" / "user"


def unit_path() -> Path:
    return _unit_dir() / UNIT_NAME


def _cli_path() -> str:
    return os.path.abspath(sys.argv[0]) if sys.argv and sys.argv[0] else "codex-auto-resume"


def install_unit(
    codex_bin: Optional[str], documentation: str = "https://github.com/lutzkind/codex-auto-resume"
) -> Path:
    from . import paths

    paths.ensure_dirs()
    _unit_dir().mkdir(parents=True, exist_ok=True)
    cli = _cli_path()
    if shutil.which("codex-auto-resume"):
        cli = shutil.which("codex-auto-resume") or cli
    content = UNIT_TEMPLATE.format(
        documentation=documentation,
        python=sys.executable,
        cli=cli,
        codex_bin=codex_bin or "codex",
        stdout=str(paths.log_file()).replace("%", "%%"),
    )
    target = unit_path()
    if target.exists():
        target.replace(target.with_suffix(target.suffix + ".bak"))
    target.write_text(content, encoding="utf-8")
    _systemctl("daemon-reload")
    _systemctl("enable", UNIT_NAME)
    return target


def uninstall_unit() -> None:
    _systemctl("disable", "--now", UNIT_NAME)
    target = unit_path()
    if target.exists():
        target.unlink()
    _systemctl("daemon-reload")
    if target.exists():
        raise RuntimeError(f"could not remove {target}")


def service_state() -> dict:
    active = _systemctl("is-active", UNIT_NAME, check=False).strip()
    enabled = _systemctl("is-enabled", UNIT_NAME, check=False).strip()
    return {"active": active, "enabled": enabled, "unit": str(unit_path())}


def _systemctl(*args: str, check: bool = True) -> str:
    try:
        completed = subprocess.run(
            ["systemctl", "--user", *args],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as error:
        if check:
            raise RuntimeError(f"systemctl --user {' '.join(args)} failed: {error}") from error
        return "unavailable"
    if check and completed.returncode != 0:
        raise RuntimeError(
            f"systemctl --user {' '.join(args)} failed: {completed.stdout.strip()}"
        )
    return completed.stdout
